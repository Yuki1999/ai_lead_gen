def upsert_agent_session(
    session_id: str, *, title: str | None = None, actor: str = ""
) -> dict[str, Any]:
    """Create the session on first use, otherwise bump its activity time. A
    provided title overwrites (renames); omitting it leaves the title alone."""
    now = _now()
    with connect() as connection:
        connection.execute(
            """
            INSERT INTO agent_sessions (session_id, title, created_by, created_at, updated_at)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (session_id) DO UPDATE SET updated_at = EXCLUDED.updated_at
            """,
            (session_id, title or "", actor, now, now),
        )
        if title is not None:
            connection.execute(
                "UPDATE agent_sessions SET title = %s, updated_at = %s WHERE session_id = %s",
                (title, now, session_id),
            )
        row = connection.execute(
            "SELECT * FROM agent_sessions WHERE session_id = %s", (session_id,)
        ).fetchone()
    return _row_to_dict(row)


def list_agent_sessions(limit: int = 200) -> list[dict[str, Any]]:
    """Every agent session (team-shared), most recently active first."""
    with connect() as connection:
        rows = connection.execute(
            """
            SELECT s.*,
                (SELECT COUNT(*) FROM agent_turns t WHERE t.session_id = s.session_id) AS turn_count
            FROM agent_sessions s
            ORDER BY s.updated_at DESC
            LIMIT %s
            """,
            (limit,),
        ).fetchall()
    return [_row_to_dict(row) for row in rows]


def get_agent_session(session_id: str) -> dict[str, Any] | None:
    with connect() as connection:
        row = connection.execute(
            "SELECT * FROM agent_sessions WHERE session_id = %s", (session_id,)
        ).fetchone()
    return _row_to_dict(row) if row else None


def list_agent_turns(session_id: str) -> list[dict[str, Any]]:
    """Turns of one session, oldest first. `payload` is decoded back to a dict."""
    with connect() as connection:
        rows = connection.execute(
            "SELECT * FROM agent_turns WHERE session_id = %s ORDER BY id ASC",
            (session_id,),
        ).fetchall()
    results: list[dict[str, Any]] = []
    for row in rows:
        item = _row_to_dict(row)
        try:
            item["payload"] = json.loads(item["payload"])
        except (ValueError, TypeError):
            item["payload"] = {}
        results.append(item)
    return results


def insert_agent_turn(
    session_id: str, *, payload: dict[str, Any], author: str = ""
) -> dict[str, Any]:
    now = _now()
    with connect() as connection:
        cursor = connection.execute(
            """
            INSERT INTO agent_turns (session_id, author, payload, created_at)
            VALUES (%s, %s, %s, %s)
            RETURNING id
            """,
            (session_id, author, json.dumps(payload, ensure_ascii=False), now),
        )
        turn_id = _scalar(cursor)
        connection.execute(
            "UPDATE agent_sessions SET updated_at = %s WHERE session_id = %s",
            (now, session_id),
        )
        row = connection.execute(
            "SELECT * FROM agent_turns WHERE id = %s", (turn_id,)
        ).fetchone()
    item = _row_to_dict(row)
    item["payload"] = payload
    return item


def delete_agent_session(session_id: str) -> bool:
    """Delete a session and its turns (children first — PG enforces order)."""
    with connect() as connection:
        row = connection.execute(
            "SELECT id FROM agent_sessions WHERE session_id = %s", (session_id,)
        ).fetchone()
        if row is None:
            return False
        connection.execute("DELETE FROM agent_turns WHERE session_id = %s", (session_id,))
        connection.execute("DELETE FROM agent_sessions WHERE session_id = %s", (session_id,))
    return True


