# ── Connection pool ────────────────────────────────────
#
# The app talks to PostgreSQL through a process-wide connection pool. Every DB
# helper uses `with connect() as connection:` - the pool hands out a connection,
# and on clean block exit the transaction commits (rolls back on exception) and
# the connection returns to the pool. This gives proper concurrency for the
# threadpool FastAPI runs sync endpoints in.

def _conninfo() -> str:
    """Resolve the PostgreSQL connection string.

    Prefers a full DSN in MEDBOT_DATABASE_URL; otherwise assembles one from
    discrete MEDBOT_DB_* parts (handy in compose where they're set separately).
    """
    url = os.getenv("MEDBOT_DATABASE_URL", "").strip()
    if url:
        return url
    host = os.getenv("MEDBOT_DB_HOST", "postgres")
    port = os.getenv("MEDBOT_DB_PORT", "5432")
    name = os.getenv("MEDBOT_DB_NAME", "medbot")
    user = os.getenv("MEDBOT_DB_USER", "medbot")
    password = os.getenv("MEDBOT_DB_PASSWORD", "medbot")
    return f"host={host} port={port} dbname={name} user={user} password={password}"


_pool: ConnectionPool | None = None


def _get_pool() -> ConnectionPool:
    global _pool
    if _pool is None:
        _pool = ConnectionPool(
            conninfo=_conninfo(),
            min_size=1,
            max_size=int(os.getenv("MEDBOT_DB_POOL_MAX", "10")),
            kwargs={"row_factory": dict_row},
            open=True,
        )
    return _pool


def _reset_pool() -> None:
    """Close and drop the pool (tests use this to rebind to a fresh DSN)."""
    global _pool
    if _pool is not None:
        try:
            _pool.close()
        finally:
            _pool = None


def connect():
    """Return a pooled connection context manager (`with connect() as conn:`)."""
    return _get_pool().connection()


def _scalar(cursor: psycopg.Cursor) -> Any:
    """Read the first column of the first row (dict rows have no positional [0])."""
    row = cursor.fetchone()
    if row is None:
        return None
    return next(iter(row.values()))


