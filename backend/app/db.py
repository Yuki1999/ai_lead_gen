def reset_for_tests() -> None:
    """Wipe every table and re-seed default auth — per-test isolation for PG."""
    init_db()
    with connect() as connection:
        connection.execute(
            "TRUNCATE " + ", ".join(_ALL_TABLES) + " RESTART IDENTITY CASCADE"
        )
    seed_auth()


def insert_lead(lead: CandidateLead) -> dict[str, Any]:
    now = _now()
    payload = asdict(lead) | {"created_at": now, "updated_at": now}
    # Canonicalize region/country to the public standard (UN M49 regions,
    # ISO 3166-1 country names) so every write path — Agent add_leads, real web
    # search, seeds, manual — stores values that match the filter taxonomy and
    # infers the region from the country when the caller didn't set one cleanly.
    from app.geo import normalize_geo

    payload["region"], payload["country"] = normalize_geo(
        str(payload.get("region") or ""), str(payload.get("country") or "")
    )
    # Resolve and persist lead_type at insert time instead of leaving it blank
    # and re-inferring on every email render — the classification needs to be
    # a stable, queryable column for filtering/dashboards/scoring-rule choice.
    if not str(payload.get("lead_type") or "").strip():
        payload["lead_type"] = infer_lead_type(lead)
    # Every lead-creation path constructs a CandidateLead with the "new"
    # default; apply the configured score thresholds here so a lead's initial
    # status actually reflects its score instead of always starting at "new".
    if payload["status"] == "new":
        payload["status"] = status_for_score(int(payload["score"]), lead_type=payload.get("lead_type"))
    with connect() as connection:
        cursor = connection.execute(
            """
            INSERT INTO leads (
                company_name, region, country, website, contact_name, email, category,
                match_reason, source, score, status, notes, lead_type, created_at, updated_at
            )
            VALUES (
                %(company_name)s, %(region)s, %(country)s, %(website)s, %(contact_name)s, %(email)s, %(category)s,
                %(match_reason)s, %(source)s, %(score)s, %(status)s, %(notes)s, %(lead_type)s, %(created_at)s, %(updated_at)s
            )
            RETURNING id
            """,
            payload,
        )
        new_id = _scalar(cursor)
        return get_lead(new_id, connection=connection)


# Whitelist of external sort keys → SQL expressions. Values are hard-coded
# server strings, so string-interpolating them into ORDER BY is safe.
_SORT_EXPRS = {
    "id": "l.id",
    "score": "l.score",
    "company_name": "l.company_name",
    "country": "l.country",
    "region": "l.region",
    "status": "l.status",
    "category": "l.category",
    "created_at": "l.created_at",
    "updated_at": "l.updated_at",
    "reply_count": "reply_count",  # derived column, present in SELECT
}

def list_leads(
    *,
    region: str | None = None,
    country: str | None = None,
    status: str | None = None,
    lead_type: str | None = None,
    q: str | None = None,
    sort: str = "id",
    order: str = "desc",
    limit: int | None = None,
    offset: int | None = None,
) -> list[dict[str, Any]]:
    filters: list[str] = []
    params: dict[str, Any] = {}
    if region:
        filters.append("region = %(region)s")
        params["region"] = region
    if country:
        filters.append("country = %(country)s")
        params["country"] = country
    if status:
        filters.append("status = %(status)s")
        params["status"] = status
    if lead_type:
        filters.append("lead_type = %(lead_type)s")
        params["lead_type"] = lead_type
    if q:
        filters.append(
            # ILIKE, not LIKE: Postgres LIKE is case-sensitive (SQLite's was not),
            # so plain LIKE made the search box miss "Dach" for "DACH Medical" and
            # match different rows depending on the caller's capitalization.
            "(company_name ILIKE %(q)s OR email ILIKE %(q)s OR country ILIKE %(q)s OR category ILIKE %(q)s)"
        )
        params["q"] = f"%{q}%"

    where = f"WHERE {' AND '.join(filters)}" if filters else ""
    sort_key = sort if sort in _SORT_EXPRS else "id"
    sort_expr = _SORT_EXPRS[sort_key]
    sort_dir = "ASC" if str(order).lower() == "asc" else "DESC"
    # Automatic secondary sort: keep results deterministic and surface newer
    # entries within ties (unless the user is already sorting by created_at/id).
    tiebreakers: list[str] = []
    if sort_key != "created_at":
        tiebreakers.append("l.created_at DESC")
    if sort_key != "id":
        tiebreakers.append("l.id DESC")
    order_clause = f"{sort_expr} {sort_dir}"
    if tiebreakers:
        order_clause += ", " + ", ".join(tiebreakers)
    limit_clause = ""
    if limit is not None:
        limit_clause = " LIMIT %(limit)s"
        params["limit"] = max(0, int(limit))
        if offset:
            limit_clause += " OFFSET %(offset)s"
            params["offset"] = max(0, int(offset))
    with connect() as connection:
        rows = connection.execute(
            f"""SELECT l.*,
                (SELECT COUNT(*) FROM reply_analyses WHERE lead_id = l.id) AS reply_count,
                (SELECT MAX(COALESCE(NULLIF(sent_at, ''), created_at))
                   FROM outreach_events
                   WHERE lead_id = l.id AND status IN ('sent', 'queued')) AS last_outreach_at
            FROM leads l
            {where} ORDER BY {order_clause}{limit_clause}""",
            params,
        ).fetchall()
    result = [_row_to_dict(row) for row in rows]
    # Attach the AI match-level badge (strong/medium/weak), caching the two rule
    # sets so a page of leads costs at most two scoring-rule reads.
    band_cache: dict[str, list[dict[str, Any]]] = {}
    for d in result:
        lt = _normalize_scoring_lead_type(d.get("lead_type"))
        if lt not in band_cache:
            band_cache[lt] = _thresholds_for(lt)
        d["match_level"] = _level_from_bands(band_cache[lt], int(d.get("score") or 0))
    return result


def count_leads(
    *,
    region: str | None = None,
    country: str | None = None,
    status: str | None = None,
    lead_type: str | None = None,
    q: str | None = None,
) -> int:
    """Total lead count for the same filter set (ignores sort/paging).

    Used so the lead list can render a pager without the caller having to fetch
    every row. Mirrors the filter clause in `list_leads` - keep them in sync.
    """
    filters: list[str] = []
    params: dict[str, Any] = {}
    if region:
        filters.append("region = %(region)s")
        params["region"] = region
    if country:
        filters.append("country = %(country)s")
        params["country"] = country
    if status:
        filters.append("status = %(status)s")
        params["status"] = status
    if lead_type:
        filters.append("lead_type = %(lead_type)s")
        params["lead_type"] = lead_type
    if q:
        filters.append(
            # ILIKE, not LIKE: Postgres LIKE is case-sensitive (SQLite's was not),
            # so plain LIKE made the search box miss "Dach" for "DACH Medical" and
            # match different rows depending on the caller's capitalization.
            "(company_name ILIKE %(q)s OR email ILIKE %(q)s OR country ILIKE %(q)s OR category ILIKE %(q)s)"
        )
        params["q"] = f"%{q}%"
    where = f"WHERE {' AND '.join(filters)}" if filters else ""
    with connect() as connection:
        return _scalar(connection.execute(f"SELECT COUNT(*) FROM leads l {where}", params))


def get_lead(
    lead_id: int,
    *,
    connection: Connection | None = None,
) -> dict[str, Any] | None:
    if connection is not None:
        row = connection.execute("SELECT * FROM leads WHERE id = %s", (lead_id,)).fetchone()
        return _finalize_lead(_row_to_dict(row)) if row else None
    with connect() as conn:
        row = conn.execute("SELECT * FROM leads WHERE id = %s", (lead_id,)).fetchone()
        return _finalize_lead(_row_to_dict(row)) if row else None


def _finalize_lead(d: dict[str, Any]) -> dict[str, Any]:
    """Attach the AI match-level badge to a single lead dict."""
    d["match_level"] = match_level_for_score(int(d.get("score") or 0), d.get("lead_type"))
    return d


def update_lead(
    lead_id: int,
    *,
    status: str | None = None,
    notes: str | None = None,
    lead_type: str | None = None,
) -> dict[str, Any] | None:
    current = get_lead(lead_id)
    if current is None:
        return None

    updated_status = status if status is not None else current["status"]
    updated_notes = notes if notes is not None else current["notes"]
    updated_lead_type = lead_type if lead_type is not None else current["lead_type"]
    with connect() as connection:
        connection.execute(
            """
            UPDATE leads
            SET status = %s, notes = %s, lead_type = %s, updated_at = %s
            WHERE id = %s
            """,
            (updated_status, updated_notes, updated_lead_type, _now(), lead_id),
        )
        return get_lead(lead_id, connection=connection)


# Outreach sources that are REPLIES to a prospect's inbound message (not first-touch
# or follow-up cold outreach). Delivering one must not flip the lead to 'emailed'.
_REPLY_SOURCES = {"reply_draft", "reply_manual"}


def insert_outreach_event(
    lead_id: int,
    email: RenderedEmail,
    *,
    status: str = "recorded",
    message_id: str = "",
    source: str = "manual",
    attach_brochure: bool = False,
) -> dict[str, Any]:
    with connect() as connection:
        cursor = connection.execute(
            """
            INSERT INTO outreach_events (lead_id, subject, body, sent_to, region, status, message_id, source, attach_brochure, created_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id
            """,
            (lead_id, email.subject, email.body, email.sent_to, email.region, status, message_id, source, int(attach_brochure), _now()),
        )
        event_id = _scalar(cursor)
        # Replies keep the lead's reply-derived status (interested/human_review/…);
        # only first-touch/follow-up cold outreach flips the lead to 'emailed'.
        if status == "sent" and source not in _REPLY_SOURCES:
            connection.execute(
                "UPDATE leads SET status = %s, updated_at = %s WHERE id = %s",
                ("emailed", _now(), lead_id),
            )
        row = connection.execute(
            "SELECT * FROM outreach_events WHERE id = %s",
            (event_id,),
        ).fetchone()
        return _row_to_dict(row)


